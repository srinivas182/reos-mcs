/**
 * "Hey Siri, quiz me with REOS" and the Android App Action (A9.3, screen 51).
 *
 * iOS: an App Shortcut (App Intents, iOS 18+) in the app itself, no extension.
 * Saying the phrase opens `reos://practice/hands-free`.
 *
 * Android: a `shortcuts.xml` capability for Google Assistant's "open app
 * feature" ("Hey Google, open voice quiz on REOS"), opening the same link.
 *
 * Neither is offered for driving: there is no CarPlay or Android Auto entry
 * (decision 4).
 */
const fs = require('node:fs');
const path = require('node:path');
const { IOSConfig, withAndroidManifest, withDangerousMod, withStringsXml, withXcodeProject, AndroidConfig } = require('expo/config-plugins');

const LINK = 'reos://practice/hands-free';
const SWIFT_FILE = 'ReosQuizShortcut.swift';

function swift() {
  return `// Generated by plugins/with-quiz-shortcut.js (A9.3). Do not edit.
import AppIntents
import Foundation

@available(iOS 18.0, *)
struct ReosQuizMeIntent: AppIntent {
  static var title: LocalizedStringResource = "Quiz me"
  static var description = IntentDescription("Starts a hands-free voice quiz in REOS. Not for driving.")
  static var openAppWhenRun: Bool = true

  func perform() async throws -> some IntentResult & OpensIntent {
    .result(opensIntent: OpenURLIntent(URL(string: "${LINK}")!))
  }
}

@available(iOS 18.0, *)
struct ReosShortcuts: AppShortcutsProvider {
  static var appShortcuts: [AppShortcut] {
    AppShortcut(
      intent: ReosQuizMeIntent(),
      phrases: ["Quiz me with \\(.applicationName)", "Start a voice quiz in \\(.applicationName)", "Hazme preguntas con \\(.applicationName)"],
      shortTitle: "Quiz me",
      systemImageName: "mic.fill"
    )
  }
}
`;
}

function shortcutsXml(packageName) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-quiz-shortcut.js (A9.3). Do not edit. -->
<shortcuts xmlns:android="http://schemas.android.com/apk/res/android">
  <capability android:name="actions.intent.OPEN_APP_FEATURE">
    <intent android:action="android.intent.action.VIEW" android:targetPackage="${packageName}" android:targetClass="${packageName}.MainActivity">
      <url-template android:value="${LINK}{?feature}" />
      <parameter android:name="feature" android:key="feature" />
    </intent>
  </capability>
  <shortcut android:shortcutId="reos_voice_quiz" android:enabled="false" android:shortcutShortLabel="@string/reos_quiz_short">
    <capability-binding android:key="actions.intent.OPEN_APP_FEATURE">
      <parameter-binding android:key="feature" android:value="@array/reos_quiz_names" />
    </capability-binding>
  </shortcut>
</shortcuts>
`;
}

const ARRAYS = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-quiz-shortcut.js (A9.3). Do not edit. -->
<resources>
  <string-array name="reos_quiz_names">
    <item>voice quiz</item>
    <item>quiz</item>
    <item>hands-free quiz</item>
    <item>cuestionario por voz</item>
  </string-array>
</resources>
`;

function withIos(config) {
  config = withDangerousMod(config, [
    'ios',
    (c) => {
      const dir = path.join(c.modRequest.platformProjectRoot, c.modRequest.projectName);
      fs.writeFileSync(path.join(dir, SWIFT_FILE), swift());

      return c;
    },
  ]);

  return withXcodeProject(config, (c) => {
    const name = c.modRequest.projectName;
    const file = `${name}/${SWIFT_FILE}`;
    if (!c.modResults.hasFile(file)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({ filepath: file, groupName: name, project: c.modResults });
    }

    return c;
  });
}

function withAndroid(config) {
  config = withDangerousMod(config, [
    'android',
    (c) => {
      const res = path.join(c.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res');
      fs.mkdirSync(path.join(res, 'xml'), { recursive: true });
      fs.writeFileSync(path.join(res, 'xml', 'reos_shortcuts.xml'), shortcutsXml(c.android?.package ?? 'com.reos.app'));
      fs.writeFileSync(path.join(res, 'values', 'reos_quiz_arrays.xml'), ARRAYS);

      return c;
    },
  ]);
  config = withStringsXml(config, (c) => {
    c.modResults = AndroidConfig.Strings.setStringItem([{ $: { name: 'reos_quiz_short', translatable: 'false' }, _: 'Voice quiz' }], c.modResults);

    return c;
  });

  return withAndroidManifest(config, (c) => {
    const activity = AndroidConfig.Manifest.getMainActivityOrThrow(c.modResults);
    activity['meta-data'] = (activity['meta-data'] ?? []).filter((m) => m.$['android:name'] !== 'android.app.shortcuts');
    activity['meta-data'].push({ $: { 'android:name': 'android.app.shortcuts', 'android:resource': '@xml/reos_shortcuts' } });

    return c;
  });
}

module.exports = (config) => withAndroid(withIos(config));
module.exports.swift = swift;
module.exports.shortcutsXml = shortcutsXml;
