/**
 * Generates the web outputs from src/index.ts:
 *
 * - src/generated/tokens.css    CSS variables for every theme, text size and motion setting
 * - src/generated/tailwind.css  Tailwind 4 `@theme` mapping (REOS utilities + shadcn/ui names)
 * - src/generated/swatches.json Theme colours for designers and the docs
 *
 *   node scripts/build.ts          write the files
 *   node scripts/build.ts --check  fail if they're out of date (CI)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  elevation,
  focusRing,
  fontSize,
  lineHeight,
  minTouchTarget,
  motion,
  radius,
  spacing,
  textScale,
  themes,
  type SemanticColors,
  type ThemeName,
} from '../src/index.ts';

const outDir = resolve(dirname(fileURLToPath(import.meta.url)), '../src/generated');
const kebab = (s: string): string => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const rem = (px: number): string => `${px / 16}rem`;
const header = '/* Generated by packages/tokens/scripts/build.ts from src/index.ts. Do not edit. */\n';

/** shadcn/ui variable names mapped onto REOS semantic tokens, so stock components follow our themes. */
const shadcn: Record<string, keyof SemanticColors> = {
  background: 'page',
  foreground: 'text',
  card: 'surface',
  'card-foreground': 'text',
  popover: 'surface',
  'popover-foreground': 'text',
  primary: 'action',
  'primary-foreground': 'onAction',
  secondary: 'surfaceMuted',
  'secondary-foreground': 'text',
  muted: 'surfaceMuted',
  'muted-foreground': 'textMuted',
  accent: 'actionTint',
  'accent-foreground': 'text',
  destructive: 'danger',
  // shadcn uses this as red text on light backgrounds (menus, alerts), not text on a red fill.
  'destructive-foreground': 'danger',
  border: 'border',
  input: 'borderControl',
  ring: 'focus',
  sidebar: 'surface',
  'sidebar-foreground': 'text',
  'sidebar-primary': 'action',
  'sidebar-primary-foreground': 'onAction',
  'sidebar-accent': 'actionTint',
  'sidebar-accent-foreground': 'text',
  'sidebar-border': 'border',
  'sidebar-ring': 'focus',
  'chart-1': 'action',
  'chart-2': 'success',
  'chart-3': 'warning',
  'chart-4': 'danger',
  'chart-5': 'textMuted',
};

const selectors: Record<ThemeName, string> = {
  light: ":root,\n[data-theme='light']",
  dark: ".dark,\n[data-theme='dark']",
  contrast: "[data-theme='contrast']",
};

function themeBlock(name: ThemeName): string {
  const t = themes[name];
  const own = Object.entries(t).map(([k, v]) => `    --reos-${kebab(k)}: ${v};`);
  const mapped = Object.entries(shadcn).map(([k, v]) => `    --${k}: var(--reos-${kebab(v)});`);
  return `${selectors[name]} {\n    color-scheme: ${name === 'dark' ? 'dark' : 'light'};\n${own.join('\n')}\n\n    /* shadcn/ui names */\n${mapped.join('\n')}\n}`;
}

const tokensCss = `${header}
${(Object.keys(themes) as ThemeName[]).map(themeBlock).join('\n\n')}

:root {
${Object.entries(spacing).map(([k, v]) => `    --reos-space-${k}: ${rem(v)};`).join('\n')}
${Object.entries(radius).map(([k, v]) => `    --reos-radius-${k}: ${v === 999 ? '999px' : rem(v)};`).join('\n')}
${Object.entries(elevation).map(([k, v]) => `    --reos-elevation-${k}: ${v};`).join('\n')}
    --reos-motion-fast: ${motion.fast}ms;
    --reos-motion-normal: ${motion.normal}ms;
    --reos-motion-easing: ${motion.easing};
    --reos-focus-width: ${focusRing.width}px;
    --reos-focus-offset: ${focusRing.offset}px;
    --reos-touch-target: ${rem(minTouchTarget)};
    --radius: ${rem(radius.md)};
}

/* Text size chosen by the user (Standard, Large, Largest). Every rem-based size scales. */
${Object.entries(textScale).map(([k, v]) => `html[data-text-size='${k}'] {\n    font-size: ${v * 100}%;\n}`).join('\n\n')}

@media (prefers-reduced-motion: reduce) {
    :root {
        --reos-motion-fast: 0ms;
        --reos-motion-normal: 0ms;
    }
}
`;

const sizes = Object.keys(fontSize) as Array<keyof typeof fontSize>;
const tailwindCss = `${header}
/*
 * Import after 'tailwindcss' and tokens.css. Adds REOS utilities (bg-reos-surface,
 * text-reos-muted, text-body, rounded-reos-md ...) and raises Tailwind's smallest
 * text size to 14px, our minimum.
 */
@theme inline {
${(Object.keys(themes.light) as Array<keyof SemanticColors>).map((k) => `    --color-reos-${kebab(k)}: var(--reos-${kebab(k)});`).join('\n')}

${sizes.map((k) => `    --text-${kebab(k)}: ${rem(fontSize[k])};\n    --text-${kebab(k)}--line-height: ${rem(lineHeight[k])};`).join('\n')}

    /* Smallest Tailwind size is 14px, never 12px. */
    --text-xs: ${rem(fontSize.caption)};
    --text-xs--line-height: ${rem(lineHeight.caption)};

${Object.entries(radius).map(([k, v]) => `    --radius-reos-${k}: ${v === 999 ? '999px' : rem(v)};`).join('\n')}
${Object.keys(elevation).map((k) => `    --shadow-reos-${k}: var(--reos-elevation-${k});`).join('\n')}
    --spacing-touch: var(--reos-touch-target);
}
`;

const swatches = `${JSON.stringify(themes, null, 2)}\n`;

const files: Record<string, string> = { 'tokens.css': tokensCss, 'tailwind.css': tailwindCss, 'swatches.json': swatches };
const check = process.argv.includes('--check');
const stale: string[] = [];

for (const [name, content] of Object.entries(files)) {
  const path = resolve(outDir, name);
  if (check) {
    let current = '';
    try {
      current = readFileSync(path, 'utf8');
    } catch {
      // reported as stale below
    }
    if (current !== content) stale.push(name);
  } else {
    writeFileSync(path, content);
  }
}

if (stale.length) {
  console.error(`✘ Generated token files are out of date: ${stale.join(', ')}. Run 'pnpm --filter @reos/tokens build' and commit.`);
  process.exit(1);
}
console.log(check ? '✔ Generated token files are up to date.' : `✔ Wrote ${Object.keys(files).join(', ')} to src/generated/`);
